const pack = (m: Record<string, Five>): Record<string, Record<string, string>> => {
  const out: Record<string, Record<string, string>> = {};
  for (const [en, vals] of Object.entries(m)) {
    out[en] = { en };
    ORDER.forEach((code, i) => (out[en][code] = vals[i]));
  }
  return out;
};

