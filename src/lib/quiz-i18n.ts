const term = (s: string, code: string): string => TERMS[s.trim()]?.[code] ?? s.trim();

/** Translate an option label, handling "A & B", "A + B" and comma lists. */
export function translateOption(text: string, code: string): string {
  if (!code || code === "en") return text;
  if (TERMS[text]) return TERMS[text][code] ?? text;
  const parts = text.split(/(\s&\s|\s\+\s|,\s)/);
  if (parts.length === 1) return text;
  return parts.map((p, i) => (i % 2 === 1 ? p : term(p, code))).join("");
}

/** Translate a question prompt. */
export function translatePrompt(text: string, code: string): string {
  if (!code || code === "en") return text;
  const direct = PROMPTS[text]?.[code];
  if (direct) return direct;
  for (const tpl of TEMPLATES) {
    const m = text.match(tpl.re);
    if (m) {
      const fn = tpl.out[code];
      if (fn) return fn(m, (s) => term(s, code));
    }
  }
  return text;
}
